extern "C" int aot_offline_smc_check(void * /*sh4ctx*/, u32 guestAddr, u32 smcSize, u32 expectedHash)
{
	if (smcSize == 0)
		return 0;
	u8 *ptr = GetMemPtr(guestAddr, smcSize);
	if (ptr == nullptr)
		return 1;
	const u32 live = shilVmHashBytes(ptr, smcSize);
	return live == expectedHash ? 0 : 1;
}

