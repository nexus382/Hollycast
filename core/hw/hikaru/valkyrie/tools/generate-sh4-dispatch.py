"""Regenerate the checked-in dispatch names; ordinary builds need no generator.

The C preprocessor expands the descriptor macros. Only the resulting marked
descriptors are collected; instruction bodies are never parsed or copied.
Run with --check to verify the checked-in list without changing it.
"""
import argparse
import pathlib
import re
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
parser.add_argument("--compiler", default="clang")
args = parser.parse_args()
cpu = pathlib.Path(__file__).resolve().parents[1] / "src/cpu/sh"
expanded = subprocess.check_output([
    args.compiler, "-E", "-P", "-x", "c",
    "-DIDEF(mask,match,name)=HIKARU_DESCRIPTOR(mask,match,name)",
    str(cpu / "sh-insns-desc.h"),
], text=True)
descriptors = re.findall(
    r"\bHIKARU_DESCRIPTOR\s*\(\s*([^,]+),\s*([^,]+),\s*([A-Za-z_]\w*)\s*\)", expanded)
if len(descriptors) != len(re.findall(r"\bHIKARU_DESCRIPTOR\s*\(", expanded)):
    raise SystemExit("Unsupported descriptor syntax")
fp_only = {}
for mask, match, name in descriptors:
    # A shared handler stays in integer dispatch if any descriptor can match
    # outside 0xFxxx. Preserve first-seen order so existing enum IDs stay stable.
    is_fp = (int(mask, 0) & 0xF000) == 0xF000 and (int(match, 0) & 0xF000) == 0xF000
    fp_only[name] = fp_only.get(name, True) and is_fp
names = ["invalid", *fp_only]
if not 1 < len(names) <= 65535:
    raise SystemExit("Unexpected descriptor count")
text = """// SPDX-License-Identifier: GPL-3.0-or-later
// Copyright 2026 The Hollycast Authors
// Portions Copyright 2026 The Hollycast Authors
// Generated by tools/generate-sh4-dispatch.py from sh-insns-desc.h.
// Deliberately no include guard: define both SH4_DISPATCH_HANDLER and
// SH4_DISPATCH_FP_HANDLER before including.
""" + "".join(
    f"SH4_DISPATCH_{'FP_' if fp_only.get(name, False) else ''}HANDLER({name})\n"
    for name in names)
output = cpu / "sh-dispatch-list.h"
if args.check:
    if output.read_text() != text:
        raise SystemExit("SH4 dispatch list is stale; run tools/generate-sh4-dispatch.py")
else:
    output.write_text(text)
print(f"SH4 dispatch list: {len(names)} handlers, {sum(fp_only.values())} FP-only")
