"""Regenerate the checked-in dispatch names; ordinary builds need no generator.

The C preprocessor expands the descriptor macros. Only the resulting marked
identifiers are collected; instruction bodies are never parsed or copied.
Run with --check to verify the checked-in list without changing it.
"""
import argparse
import pathlib
import re
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
parser.add_argument("--compiler", default="clang")
args = parser.parse_args()
cpu = pathlib.Path(__file__).resolve().parents[1] / "src/cpu/sh"
expanded = subprocess.check_output([
    args.compiler, "-E", "-P", "-x", "c",
    "-DIDEF(mask,match,name)=HIKARU_DESCRIPTOR_NAME(name)",
    str(cpu / "sh-insns-desc.h"),
], text=True)
names = ["invalid"] + list(dict.fromkeys(re.findall(
    r"\bHIKARU_DESCRIPTOR_NAME\s*\(\s*([A-Za-z_]\w*)\s*\)", expanded)))
if not 1 < len(names) <= 65535:
    raise SystemExit("Unexpected descriptor count")
text = """// SPDX-License-Identifier: GPL-3.0-or-later
// Copyright 2026 The Hollycast Authors
// Generated by tools/generate-sh4-dispatch.py from sh-insns-desc.h.
// Deliberately no include guard: define SH4_DISPATCH_HANDLER before including.
""" + "".join(f"SH4_DISPATCH_HANDLER({name})\n" for name in names)
output = cpu / "sh-dispatch-list.h"
if args.check:
    if output.read_text() != text:
        raise SystemExit("SH4 dispatch list is stale; run tools/generate-sh4-dispatch.py")
else:
    output.write_text(text)
print(f"SH4 dispatch list: {len(names)} handlers")
